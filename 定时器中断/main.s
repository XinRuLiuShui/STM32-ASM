.syntax unified
.cpu cortex-m3
.thumb

.global main
.global TIM2_IRQHandler

.section .text
.type main, %function

main:

    /*--------------------------------
     * 1. 开启 GPIOC 时钟
     *
     * RCC_APB2ENR = 0x40021018
     * GPIOCEN = bit4
     *--------------------------------*/

    ldr r0, =0x40021018
    ldr r1, [r0]
    orr r1, r1, #(1 << 4)
    str r1, [r0]


    /*--------------------------------
     * 2. 配置 PC13
     *
     * GPIOC_CRH = 0x40011004
     * PC13 对应 bit23:20
     * 0x1 = 10MHz 推挽输出
     *--------------------------------*/

    ldr r0, =0x40011004
    ldr r1, =0x00100000
    str r1, [r0]



   /*--------------------------------
     * 3. 开启 TIM2 时钟
     *
     * RCC_APB1ENR = 0x4002101C
     * TIM2EN = bit0
     *--------------------------------*/

    ldr r0, =0x4002101C
    ldr r1,[r0]
    orr r1,r1,#1
    str r1,[r0]

   /*--------------------------------
     * 4. 配置 TIM2 预分频器 PSC
     *
     * TIM2_PSC = 0x40000028
     *
     * 当前时钟按 72MHz 计算
     * PSC = 7199
     * 计数频率 = 72MHz / 7200 = 10kHz
     *--------------------------------*/
    ldr r0, =0x40000028
    ldr r1, =7199
    str r1,[r0]

   /*--------------------------------
     * 5. 配置自动重装寄存器 ARR
     *
     * TIM2_ARR = 0x4000002C
     * ARR = 9999
     *
     * 10000 次计数产生一次更新
     * 定时周期约为 1 秒
     *--------------------------------*/


    ldr r0, =0x4000002C
    ldr r1, =9999
    str r1,[r0]


    /*--------------------------------
     * 6. 清零计数器 CNT
     *
     * TIM2_CNT = 0x40000024
     *--------------------------------*/

    ldr r0, =0x40000024
    mov r1, #0
    str r1, [r0]


    /*--------------------------------
     * 7. 清除可能残留的 UIF 标志
     *
     * TIM2_SR = 0x40000010
     * UIF = bit0
     * 写 0 清除 UIF
     *--------------------------------*/

    ldr r0, =0x40000010
    mov r1, #0
    str r1, [r0]

    /*--------------------------------
     * 8. 允许 TIM2 更新中断
     *
     * TIM2_DIER = 0x4000000C
     * UIE = bit0
     *--------------------------------*/

    ldr r0, =0x4000000C
    mov r1, #1
    str r1, [r0]


    /*--------------------------------
     * 9. 在 NVIC 中使能 TIM2 中断
     *
     * NVIC_ISER0 = 0xE000E100
     * TIM2 的 IRQ 编号 = 28
     *--------------------------------*/

    ldr r0, =0xE000E100
    ldr r1, =(1 << 28)
    str r1, [r0]

    /*--------------------------------
     * 10. 启动 TIM2
     *
     * TIM2_CR1 = 0x40000000
     * CEN = bit0
     *--------------------------------*/

    ldr r0, =0x40000000
    mov r1, #1
    str r1, [r0]

    /*--------------------------------
     * 11. 主程序进入无限循环
     *
     * LED 由中断服务程序控制
     *--------------------------------*/
main_loop:
    b main_loop

.size main, . - main

/*====================================
 * TIM2 中断服务程序
 *====================================*/

.type TIM2_IRQHandler, %function

TIM2_IRQHandler:

    /* 1. 清除 TIM2 更新中断标志 UIF */

    ldr r0, =0x40000010
    mov r1, #0
    str r1, [r0]


    /* 2. 翻转 PC13 输出状态
     *
     * GPIOC_ODR = 0x4001100C
     * bit13 = 0：LED 亮
     * bit13 = 1：LED 灭
     */

    ldr r0, =0x4001100C
    ldr r1, [r0]
    eor r1, r1, #0x2000
    str r1, [r0]


    /* 3. 从中断返回 */

    bx lr

.size TIM2_IRQHandler, . - TIM2_IRQHandler
